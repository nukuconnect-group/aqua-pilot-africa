const SELECT_PREFIXES: Array<[RegExp, string]> = [
  [/^sélectionner (?:un|une|le|la|l')\s*/i, 'Select '],
  [/^rechercher (?:un|une|le|la|l')\s*/i, 'Search '],
  [/^choisir (?:un|une|le|la|l')\s*/i, 'Choose '],
];

const normalize = (s: string) =>
  s
    .trim()
    .toLowerCase()
    .replace(/\s+/g, ' ')
    .replace(/[*:]+$/g, '')
    .trim();

const DICT: Record<string, string> = {};
for (const [k, v] of Object.entries(RAW)) DICT[normalize(k)] = v;

const matchCase = (source: string, translated: string) => {
  if (source === source.toUpperCase() && /[A-ZÉÈÀÙÔÎÇ]/.test(source)) return translated.toUpperCase();
  return translated;
};

/** Traduit une chaîne française en anglais, ou renvoie null si inconnue. */
export const translateFrToEn = (input: string): string | null => {
  const original = input;
  const trimmed = original.trim();
  if (!trimmed || trimmed.length > 140) return null;
  if (!/[a-zA-Zà-ÿÀ-Ÿ]/.test(trimmed)) return null;

  const leading = original.slice(0, original.indexOf(trimmed[0]));
  const trailing = original.slice(leading.length + trimmed.length);

  // Suffixes de ponctuation conservés (: * ? ! ...)
  const m = trimmed.match(/^(.*?)([\s*:?!.…]*)$/s);
  const core = m ? m[1] : trimmed;
  const suffix = m ? m[2] : '';

  const direct = DICT[normalize(trimmed)];
  if (direct) return leading + matchCase(trimmed, direct) + suffix.replace(/\.\.\.$|…$/, (x) => x) + trailing;

  const byCore = DICT[normalize(core)];
  if (byCore) return leading + matchCase(core, byCore) + suffix + trailing;

  for (const [re, prefix] of SELECT_PREFIXES) {
    if (re.test(core)) {
      const rest = core.replace(re, '');
      const restKey = normalize(rest.replace(/\s*\(.*\)\s*$/, ''));
      const restTranslated = DICT[restKey];
      if (restTranslated) {
        const paren = rest.match(/\(([^)]*)\)\s*$/);
        const parenText = paren ? ` (${DICT[normalize(paren[1])] ?? paren[1]})` : '';
        return leading + prefix + restTranslated.toLowerCase() + parenText + suffix + trailing;
      }
    }
  }

  // "Libellé (unité)" -> traduit le libellé, garde l'unité
  const withUnit = core.match(/^(.+?)\s*\(([^)]+)\)$/);
  if (withUnit) {
    const base = DICT[normalize(withUnit[1])];
    if (base) return leading + `${base} (${withUnit[2]})` + suffix + trailing;
  }

  return null;
};

export const hasTranslation = (input: string) => translateFrToEn(input) !== null;
